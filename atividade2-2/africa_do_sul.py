from turtle import *

t = Turtle()

#Desenhando o fundo branco
t.pu()
t.goto(-225, 150)
t.pd()
t.seth(0)
t.color("white")
t.begin_fill()
for cont in range(2):
    t.fd(450)
    t.rt(90)
    t.fd(300)
    t.rt(90)
t.end_fill()

#Desenhando a faixa vermelha (topo)
t.pu()
t.goto(-225, 150)
t.pd()
t.color("#DE3831")
t.begin_fill()
t.goto(225, 150)
t.goto(218, 99)
t.goto(-82, 29)
t.goto(-225, 150)
t.end_fill()

#Desenhando a faixa azul (base)
t.pu()
t.goto(-225, -150)
t.pd()
t.color("#002395")
t.begin_fill()
t.goto(225, -150)
t.goto(218, -99)
t.goto(-82, -29)
t.goto(-225, -150)
t.end_fill()

#Desenhando o triangulo preto
t.pu()
t.goto(-225, 150)
t.pd()
t.color("black")
t.begin_fill()
t.goto(-225, -150)
t.goto(-95, 0)
t.goto(-225, 150)
t.end_fill()

#Desenhando a parte dourada (cima) 
t.pu()
t.goto(-82, 29)
t.pd()
t.color("#FFB612")
t.begin_fill()
t.goto(218, 99)
t.goto(232, 41)
t.goto(-68, -29)
t.goto(-82, 29)
t.end_fill()

#Desenhando a parte dourada (baixo)
t.pu()
t.goto(-68, 29)
t.pd()
t.color("#FFB612")
t.begin_fill()
t.goto(232, -41)
t.goto(218, -99)
t.goto(-82, -29)
t.goto(-68, 29)
t.end_fill()

#Desenhando a parte varde (cima)
t.pu()
t.goto(-78, 15)
t.pd()
t.color("#007A4D")
t.begin_fill()
t.goto(222, 85)
t.goto(228, 55)
t.goto(-72, -15)
t.goto(-78, 15)
t.end_fill()

#Desenhando a parte verde (baixo)
t.pu()
t.goto(-72, 15)
t.pd()
t.color("#007A4D")
t.begin_fill()
t.goto(228, -55)
t.goto(222, -85)
t.goto(-78, -15)
t.goto(-72, 15)
t.end_fill()

mainloop()
